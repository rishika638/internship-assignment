class LinkAnalysisRequest(BaseModel):
    url: str = Field(
        ...,
        description="Fully qualified website URL to analyze (e.g. https://dxora.com or https://stripe.com)",
        examples=["https://dxora.com", "https://stripe.com"]
    )

class CrawlSummary(BaseModel):
    title: Optional[str] = None
    meta_description: Optional[str] = None
    pages_crawled: int = 1
    total_characters_extracted: int = 0
    internal_links_discovered: List[str] = Field(default_factory=list)
    has_schema_org: bool = False
    has_open_graph: bool = False

class Telemetry(BaseModel):
    provider: str = Field(..., description="LLM provider used (gemini, openai, claude, mock)")
    model: str = Field(..., description="Model identifier")
    is_mock: bool = Field(False, description="True if response was produced by the mock engine")
    cached: bool = Field(False, description="True if response was served from cache")
    execution_time_ms: float = Field(..., description="Total execution duration in milliseconds")
    input_tokens: int = Field(0, description="Tokens used for prompt")
    output_tokens: int = Field(0, description="Tokens used for completion")
    estimated_cost_usd: float = Field(0.0, description="Estimated total cost in USD")
    content_hash: str = Field(..., description="SHA-256 fingerprint of the cleaned website content")
    timestamp: str = Field(..., description="ISO 8601 timestamp of analysis")

