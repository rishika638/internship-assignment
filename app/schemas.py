from typing import List, Optional, Literal
from pydantic import BaseModel, Field, HttpUrl

# -------------------------------------------------------------
# 1. Competitor vs Brand Analysis Models
# -------------------------------------------------------------
class CompetitorInfo(BaseModel):
    name: str = Field(..., description="Name of the competitor")
    overview: str = Field(..., description="Overview and description of the competitor")
    strengths: List[str] = Field(default_factory=list, description="Observed strengths of the competitor")
    weaknesses: List[str] = Field(default_factory=list, description="Observed weaknesses or market gaps")
    market_gaps: List[str] = Field(default_factory=list, description="Gaps left open by this competitor")
    source_url: Optional[str] = Field(None, description="Evidence or reference URL if available")
    is_verified: bool = Field(False, description="True if verified from explicit website references, False if AI inferred")

class CompetitorVsBrandAnalysis(BaseModel):
    brand_name: str = Field(..., description="Identified brand or organization name")
    brand_overview: str = Field(..., description="Comprehensive overview of what the brand does")
    category: str = Field(..., description="Industry category / vertical")
    products_and_services: List[str] = Field(default_factory=list, description="Key products and services offered")
    competitors: List[CompetitorInfo] = Field(..., min_length=3, description="Minimum 3 relevant competitors")
    brand_competitive_advantages: List[str] = Field(default_factory=list, description="Key competitive edges and unique selling points")
    market_positioning_opportunities: List[str] = Field(default_factory=list, description="Strategic opportunities for market positioning")
    verified_information: List[str] = Field(default_factory=list, description="Information directly verified from site content")
    ai_generated_suggestions: List[str] = Field(default_factory=list, description="Strategic suggestions and market hypotheses generated by AI")

# -------------------------------------------------------------
# 2. Top 5 Target Search Queries Models
# -------------------------------------------------------------
PlatformType = Literal["Google", "Facebook", "Instagram", "LinkedIn", "X"]

class SearchQueryItem(BaseModel):
    query: str = Field(..., description="Customer search query")
    relevant_platforms: List[PlatformType] = Field(..., description="Supported platforms where this query is relevant")
    search_intent: str = Field(..., description="Search intent: Informational, Navigational, Commercial, or Transactional")
    business_relevance: str = Field(..., description="Why this query directly matters to the business and conversions")
    target_audience: str = Field(..., description="Specific audience segment actively searching for this query")

class Top5TargetSearchQueries(BaseModel):
    queries: List[SearchQueryItem] = Field(
        ...,
        min_length=5,
        max_length=5,
        description="Exactly five targeted customer search queries across Google, Facebook, Instagram, LinkedIn, and X. No fabricated metrics."
    )

# -------------------------------------------------------------
# 3. SEO Improvements Models
# -------------------------------------------------------------
class KeywordBreakdown(BaseModel):
    primary_keywords: List[str] = Field(default_factory=list, description="Core high-volume target keywords")
    secondary_keywords: List[str] = Field(default_factory=list, description="Supporting keywords")
    long_tail_keywords: List[str] = Field(default_factory=list, description="Specific intent long-tail queries")
    business_keywords: List[str] = Field(default_factory=list, description="Brand and direct commercial keywords")

class SupportingContentSuggestions(BaseModel):
    service_landing_pages: List[str] = Field(default_factory=list, description="Specific recommended service landing page ideas")
    industry_pages: List[str] = Field(default_factory=list, description="Vertical/industry specific page suggestions")
    faqs: List[str] = Field(default_factory=list, description="High-priority FAQ topics to answer customer queries")
    blogs: List[str] = Field(default_factory=list, description="Content marketing and thought leadership blog topics")
    location_pages: List[str] = Field(default_factory=list, description="Geographic or local landing pages if relevant")

class SEOImprovements(BaseModel):
    keywords: KeywordBreakdown = Field(..., description="Comprehensive keyword architecture")
    recommended_title: str = Field(..., description="Optimized, click-worthy SEO title tag (under 60 chars)")
    recommended_meta_description: str = Field(..., description="Engaging, conversion-focused meta description (under 160 chars)")
    supporting_content_suggestions: SupportingContentSuggestions = Field(..., description="Actionable content expansion ideas specific to the site")
    technical_and_onpage_notes: List[str] = Field(default_factory=list, description="Specific recommendations for on-page and technical SEO")

# -------------------------------------------------------------
# 4. Top 5 Services Models
# -------------------------------------------------------------
class ServiceItem(BaseModel):
    service_name: str = Field(..., description="Title or name of the service")
    description: str = Field(..., description="Clear explanation of the service offering")
    target_industry: str = Field(..., description="Primary vertical or industry sector")
    target_customer: str = Field(..., description="Typical ideal buyer or user role")
    main_benefit: str = Field(..., description="Core value proposition or outcome delivered")
    is_explicitly_stated: bool = Field(..., description="True if explicitly found on website, False if inferred by AI")
    evidence_or_source: Optional[str] = Field(None, description="Extracted textual excerpt or reference page")

class Top5Services(BaseModel):
    services: List[ServiceItem] = Field(
        ...,
        min_length=1,
        max_length=5,
        description="Up to five key services with explicit labeling of stated vs inferred"
    )

# -------------------------------------------------------------
# 5. Target Audience Models
# -------------------------------------------------------------
class TargetAudience(BaseModel):
    primary_audience: str = Field(..., description="Main customer or client demographic/firmographic")
    secondary_audience: str = Field(..., description="Secondary or adjacent user groups")
    industry_segments: List[str] = Field(default_factory=list, description="Target industry verticals")
    business_types: List[str] = Field(default_factory=list, description="B2B, B2C, Enterprise, SMBs, Startups, etc.")
    customer_profiles: List[str] = Field(default_factory=list, description="Key personas / job titles (e.g. CMO, CTO, Small Business Owner)")
    geographic_focus: str = Field(..., description="Identified regional or global geographic focus")
    customer_needs: List[str] = Field(default_factory=list, description="Pain points, requirements, and desires")
    customer_challenges: List[str] = Field(default_factory=list, description="Frictions and blockers customers encounter")
    customer_interests: List[str] = Field(default_factory=list, description="Key topics, solutions, and priorities")
    recommended_marketing_segments: List[str] = Field(default_factory=list, description="Recommended audience segments for campaigns")
    extracted_facts: List[str] = Field(default_factory=list, description="Directly extracted audience statements from website")
    ai_inferences: List[str] = Field(default_factory=list, description="Strategic audience inferences synthesized by AI")

